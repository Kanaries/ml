#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'scripts/sklearn-1.5-estimators.json'), 'utf8'));

const aliases = new Map([
    ['DBScan', 'DBSCAN'],
    ['HDBScan', 'HDBSCAN'],
    ['KNearestNeighbors', 'KNeighborsClassifier'],
    ['LDA', 'LinearDiscriminantAnalysis'],
    ['LLE', 'LocallyLinearEmbedding'],
    ['QDA', 'QuadraticDiscriminantAnalysis'],
    ['RidgeRegression', 'Ridge'],
    ['LassoRegression', 'Lasso'],
]);

// Ask TypeScript for the real public export graph rooted at src/index.ts.
// Recursing namespace exports (Bayes, Tree, ...) avoids counting an `export
// class` declaration that the package entry point does not actually expose.
const exported = new Set();
const entryPath = path.join(root, 'src/index.ts');
const program = ts.createProgram([entryPath], {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Node10,
});
const checker = program.getTypeChecker();
const entry = program.getSourceFile(entryPath);
const seen = new Set();
function collectPublicClasses(symbol) {
    if (!symbol || seen.has(symbol)) return;
    seen.add(symbol);
    const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
    if (target.flags & ts.SymbolFlags.Class) {
        exported.add(aliases.get(target.name) ?? target.name);
        return;
    }
    if (target.flags & (ts.SymbolFlags.Module | ts.SymbolFlags.NamespaceModule | ts.SymbolFlags.ValueModule)) {
        for (const nested of checker.getExportsOfModule(target)) collectPublicClasses(nested);
    }
}
for (const symbol of checker.getExportsOfModule(checker.getSymbolAtLocation(entry))) collectPublicClasses(symbol);

const byKind = new Map([
    ['estimator', snapshot.estimators.filter(row => row.kind === 'estimator').map(row => row.name)],
    ['transformer', snapshot.estimators.filter(row => row.kind === 'transformer').map(row => row.name)],
]);

const lines = [
    '# sklearn 1.5 estimator coverage',
    '',
    '> Generated by `npm run coverage:sklearn` from the checked-in scikit-learn ' +
        snapshot.sklearnVersion + ' `all_estimators()` snapshot. Do not edit coverage numbers by hand.',
    '> `transformer` means an `all_estimators()` class that exposes transform; the estimator row contains the remaining classes. Public coverage is resolved from the package root export graph.',
    '',
    '| Kind | Covered | Denominator | Coverage |',
    '|---|---:|---:|---:|',
];
const details = [];
for (const [kind, names] of byKind) {
    const covered = names.filter(name => exported.has(name));
    const missing = names.filter(name => !exported.has(name));
    lines.push(`| ${kind} | ${covered.length} | ${names.length} | ${(100 * covered.length / names.length).toFixed(1)}% |`);
    details.push('', `## Missing ${kind}s (${missing.length})`, '', missing.join(' · '));
}
lines.push(...details, '');
const report = lines.join('\n');
const reportPath = path.join(root, 'docs/coverage-vs-sklearn.md');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(reportPath) ? fs.readFileSync(reportPath, 'utf8') : '';
    if (current !== report) {
        console.error('docs/coverage-vs-sklearn.md is stale; run npm run coverage:sklearn');
        process.exit(1);
    }
} else {
    fs.writeFileSync(reportPath, report);
}
console.log(report);
